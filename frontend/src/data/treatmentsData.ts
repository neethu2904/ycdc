export function searchTreatments(query: string, list: Treatment[] = MOCK_SERVICES): Treatment[] {
  const cleanQuery = query.trim().toLowerCase();
  if (!cleanQuery) return [];
  
  return list.filter((t) => {
    return (
      t.name.toLowerCase().includes(cleanQuery) ||
      (t.treats && t.treats.toLowerCase().includes(cleanQuery)) ||
      (t.description && t.description.toLowerCase().includes(cleanQuery)) ||
      (t.category_name && t.category_name.toLowerCase().includes(cleanQuery)) ||
      (t.science && t.science.toLowerCase().includes(cleanQuery))
    );
  });
}
